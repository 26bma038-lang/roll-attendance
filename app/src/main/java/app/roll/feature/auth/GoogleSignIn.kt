package app.roll.feature.auth

import android.annotation.SuppressLint
import android.content.Context
import androidx.credentials.ClearCredentialStateRequest
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import androidx.credentials.exceptions.GetCredentialException
import androidx.credentials.exceptions.NoCredentialException
import app.roll.domain.college.NithConfig
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import dagger.hilt.android.qualifiers.ApplicationContext
import javax.inject.Inject
import javax.inject.Singleton

sealed interface GoogleTokenResult {
    data class Success(val idToken: String) : GoogleTokenResult
    data object Cancelled : GoogleTokenResult
    data class Failure(val message: String) : GoogleTokenResult
}

/** "Continue with Google" through Android Credential Manager. */
@Singleton
class GoogleSignIn @Inject constructor(
    @ApplicationContext private val appContext: Context,
) {
    private val credentialManager = CredentialManager.create(appContext)

    /**
     * The OAuth web client id generated by the google-services plugin from google-services.json.
     * Looked up by name because the resource only exists once Firebase is configured.
     */
    @SuppressLint("DiscouragedApi")
    private fun webClientId(): String? {
        val id = appContext.resources.getIdentifier("default_web_client_id", "string", appContext.packageName)
        return if (id == 0) null else appContext.getString(id)
    }

    /** Needs an Activity context to show the account picker. */
    suspend fun requestIdToken(activityContext: Context): GoogleTokenResult {
        val clientId = webClientId()
            ?: return GoogleTokenResult.Failure(
                "Google sign-in isn't enabled for this build. Enable it in the Firebase console and download google-services.json again.",
            )
        val request = GetCredentialRequest.Builder()
            .addCredentialOption(
                GetSignInWithGoogleOption.Builder(clientId)
                    // Only offer @nith.ac.in accounts in the picker. AppSession checks again after sign-in.
                    .setHostedDomainFilter(NithConfig.DOMAIN)
                    .build(),
            )
            .build()
        return try {
            val credential = credentialManager.getCredential(activityContext, request).credential
            if (credential is CustomCredential && credential.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
                GoogleTokenResult.Success(GoogleIdTokenCredential.createFrom(credential.data).idToken)
            } else {
                GoogleTokenResult.Failure("That account type isn't supported. Choose a Google account.")
            }
        } catch (_: GetCredentialCancellationException) {
            GoogleTokenResult.Cancelled
        } catch (_: NoCredentialException) {
            GoogleTokenResult.Failure("No @nith.ac.in account on this phone. Add your college Google account in system settings, then try again.")
        } catch (e: GetCredentialException) {
            GoogleTokenResult.Failure("Couldn't sign in with Google. ${e.errorMessage ?: "Try again."}")
        }
    }

    suspend fun clearState() {
        runCatching { credentialManager.clearCredentialState(ClearCredentialStateRequest()) }
    }
}
